#!/usr/bin/env python3
"""Bake the playground into soupsend, so the binary is the whole thing.

Without this soupsend is a server with nothing to serve unless you happen to
have a checkout beside it. With it, one binary gives you the page and the NDI
output together, which is the only sense in which a browser can have a bridge
"built in".

Run by the Makefile; the output is generated, not committed, so it can never
drift from the page it is a copy of.

    python3 embed.py <site-root> > embedded.c
"""
import sys, pathlib

FILES = [
    "playground.html", "lucid.css", "stack.css", "lucid.js", "stack.js",
    "playground.webmanifest", "icons/soup.svg", "icons/soup-180.png",
    "icons/soup-192.png",
]
MIME = {
    ".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8",
    ".js": "text/javascript; charset=utf-8", ".svg": "image/svg+xml",
    ".png": "image/png", ".webmanifest": "application/manifest+json",
}

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "..")
out = sys.stdout
out.write('// Generated by embed.py. Do not edit, do not commit.\n')
out.write('#include "embedded.h"\n\n')

kept = []
for rel in FILES:
    p = root / rel
    if not p.is_file():
        print(f"embed.py: missing {p}", file=sys.stderr)
        continue
    data = p.read_bytes()
    ident = "f_" + rel.replace("/", "_").replace(".", "_").replace("-", "_")
    out.write(f"static const unsigned char {ident}[] = {{")
    out.write(",".join(str(b) for b in data))
    out.write("};\n")
    kept.append((rel, MIME.get(p.suffix, "application/octet-stream"), ident, len(data)))

out.write("\nconst EmbFile embedded[] = {\n")
for rel, mime, ident, n in kept:
    out.write(f'    {{ "/{rel}", "{mime}", {ident}, {n} }},\n')
out.write("};\nconst int embedded_n = %d;\n" % len(kept))
print(f"embed.py: baked {len(kept)} files, {sum(k[3] for k in kept)/1024:.0f} KiB",
      file=sys.stderr)
